    public static void saveTail(LuaClosure func, String outFile) {
        int skip = func.p.tailPos;
        if (skip >= 0 && func.sourceFile != null) {
            File file = new File(func.sourceFile);
            if (file.exists()) {
                try {
                    FileInputStream in = new FileInputStream(file);
                    in.skip(skip);
                    FileOutputStream out = new FileOutputStream(outFile);
                    byte[] buf = new byte[65536];
                    while (true) {
                        int read = in.read(buf);
                        if (read > 0) {
                            out.write(buf, 0, read);
                        } else {
                            out.close();
                            in.close();
                            return;
                        }
                    }
                } catch (IOException e) {
                    Log.d("Fail save tail to " + outFile, e);
                }
            }
        }
    }

    static class PrintState {
        String level;
        byte[] used;
        int func = 0;
        int line = -1;

        PrintState() {
        }
    }

    public static void printFunction(Prototype prototype, String level, PrintState state) {
        Prototype[] p = prototype.p;
        int n = p.length;
        printHeader(prototype, level);
        printUpValues(prototype, level);
        printCode(prototype, level, state);
        String nextLevel = String.valueOf(level) + "\t";
        int offset = state.func;
        state.func = offset + n;
        for (int i = 0; i < n; i++) {
            ps.print(ListManager.NEW_LINE);
            ps.print(level);
            ps.print(".func F" + (offset + i) + ' ');
            printFunction(p[i], nextLevel, state);
            ps.print(level);
            ps.print(".end ; F" + (offset + i) + ListManager.NEW_LINE);
        }
    }

    private static void format(String s, int maxcols) {
        int n = s.length();
        if (n > maxcols) {
            ps.print(s.substring(0, maxcols));
            return;
        }
        ps.print(s);
        int i = maxcols - n;
        while (true) {
            i--;
            if (i >= 0) {
                ps.print(' ');
            } else {
                return;
            }
        }
    }

    public static void printState(LuaClosure cl, int pc, LuaValue[] stack, int top, Varargs varargs) {
        PrintStream prev = ps;
        ByteArrayOutputStream baos = new ByteArrayOutputStream();
        ps = new PrintStream(baos);
        printOpCode(cl.p, pc);
        ps.flush();
        ps.close();
        ps = prev;
        format(baos.toString(), 50);
        printStack(stack, top, varargs);
        ps.println();
    }

    public static void printStack(LuaValue[] stack, int top, Varargs varargs) {
        String str;
        ps.print('[');
        for (int i = 0; i < stack.length; i++) {
            LuaValue v = stack[i];
            if (v == null) {
                ps.print(STRING_FOR_NULL);
            } else {
                switch (v.type()) {
                    case 4:
                        LuaString s = v.checkstring();
                        PrintStream printStream = ps;
                        if (s.length() < 48) {
                            str = s.tojstring();
                        } else {
                            str = String.valueOf(s.substring(0, 32).tojstring()) + "...+" + (s.length() - 32) + 'b';
                        }
                        printStream.print(str);
                        break;
                    default:
                        ps.print(v.tojstring());
                        break;
                }
            }
            if (i + 1 == top) {
                ps.print(']');
            }
            ps.print(" | ");
        }
        ps.print(varargs);
    }
